/**
 * renderHtml turns a PatchSentinel Report into a single self-contained HTML
 * document. No external assets, scripts, or network calls are used: all CSS is
 * inlined so the report can be attached to a CI artifact and opened offline.
 */

import { Report, FileStat, RiskHit, Finding } from "./types.js";
import {
  escapeHtml,
  ratio,
  minutes,
  verdictMeta,
  severityEmoji,
} from "./util.js";

export function renderHtml(report: Report): string {
  const v = verdictMeta(report.verdict);
  const s = report.summary;

  const metrics: Array<[string, string]> = [
    ["Files changed", String(s.filesChanged)],
    ["Lines added", `+${s.linesAdded}`],
    ["Lines removed", `-${s.linesRemoved}`],
    ["Production added", String(s.productionAdded)],
    ["Test added", String(s.testAdded)],
    ["Test-to-code ratio", ratio(s.testToCodeRatio)],
    ["Risk score", String(s.riskScore)],
    ["Repetition ratio", ratio(s.repetitionRatio)],
    ["Sensitive files", String(s.sensitiveFiles)],
    ["Est. review time", minutes(s.reviewMinutes)],
  ];

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>PatchSentinel Report — ${v.label}</title>
<style>
${styles()}
</style>
</head>
<body>
<main class="wrap">
  <header class="hero" style="border-color:${v.color}">
    <div class="verdict" style="background:${v.color}">${v.emoji} ${v.label}</div>
    <div class="hero-meta">
      <h1>PatchSentinel Report</h1>
      <p class="sub">Deterministic AI contribution quality gate · schema v${report.schemaVersion} · policy v${report.policyVersion}</p>
      <p class="hash" title="Content hash">hash: ${escapeHtml(s.contentHash)}</p>
    </div>
  </header>

  <section aria-label="Metrics">
    <div class="grid">
      ${metrics.map(metricCard).join("\n      ")}
    </div>
  </section>

  ${section("Findings", renderFindings(report.findings))}
  ${section("Risk signals", renderRisks(report.risks))}
  ${section("Files changed", renderFiles(report.files))}

  <footer>
    <p>Generated by PatchSentinel · exit code ${report.exitCode}</p>
  </footer>
</main>
</body>
</html>
`;
}

function metricCard([label, value]: [string, string]): string {
  return `<div class="card"><div class="card-value">${escapeHtml(value)}</div><div class="card-label">${escapeHtml(
    label,
  )}</div></div>`;
}

function section(title: string, body: string): string {
  return `<section aria-label="${escapeHtml(title)}">
    <h2>${escapeHtml(title)}</h2>
    ${body}
  </section>`;
}

function renderFindings(findings: Finding[]): string {
  if (findings.length === 0) {
    return `<p class="empty">No findings.</p>`;
  }
  const rows = findings
    .map(
      (f) =>
        `<li class="finding sev-${escapeHtml(f.severity)}">
        <span class="sev-badge">${severityEmoji(f.severity)} ${escapeHtml(f.severity)}</span>
        <div><strong>${escapeHtml(f.title)}</strong><p>${escapeHtml(f.detail)}</p></div>
      </li>`,
    )
    .join("\n    ");
  return `<ul class="findings">\n    ${rows}\n  </ul>`;
}

